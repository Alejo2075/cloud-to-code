import { toPascalCase } from '@cloud-to-code/reconstruction';
import type { ReconstructionPlan } from '@cloud-to-code/core';
import type { ConstructOutput } from './constructs.js';
import type { GenContext } from './context.js';
import { type GroupName } from './context.js';
import { envParameterName, isSecretishEnvName, parameterNames } from './rules/lambda.js';
import { quote } from './ts.js';
import type { GeneratedFile } from './types.js';

export const CDK_LIB_VERSION = '^2.275.0';

function kebab(name: string): string {
  return name
    .replace(/([a-z0-9])([A-Z])/g, '$1-$2')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

export function stackFileBase(plan: ReconstructionPlan): string {
  return kebab(plan.stacks[0]!.name);
}

export function stackFile(ctx: GenContext, outputs: readonly ConstructOutput[]): GeneratedFile {
  const plan = ctx.plan;
  const stack = plan.stacks[0]!;
  const byGroup = new Map<GroupName, ConstructOutput>(outputs.map((o) => [o.group, o]));
  const lines: string[] = [
    '// Generated by Cloud to Code. Review before use.',
    "import * as cdk from 'aws-cdk-lib';",
    "import { Construct } from 'constructs';",
  ];
  for (const o of outputs)
    lines.push(
      `import { ${o.className}${o.hasParameters ? `, ${o.className}Parameters` : ''} } from '../constructs/${o.group}';`,
    );
  lines.push(
    '',
    `export class ${stack.name} extends cdk.Stack {`,
    '  constructor(scope: Construct, id: string, props?: cdk.StackProps) {',
    '    super(scope, id, props);',
    '',
  );

  const compute = byGroup.get('compute');
  if (compute?.hasParameters) {
    lines.push(
      `    const parameters: ${compute.className}Parameters = { code: {}, environment: {} };`,
    );
    const fnIds = compute.construct.resourceIds
      .filter((id) => ctx.entry(id).resource.type === 'AWS::Lambda::Function')
      .sort();
    for (const id of fnIds) {
      const r = ctx.entry(id).resource;
      const names = parameterNames(ctx, id);
      const v = ctx.varName(id);
      lines.push(
        `    const ${v}CodeBucket = new cdk.CfnParameter(this, ${quote(names.bucket)}, { type: 'String', description: ${quote(`S3 bucket holding the deployment package for ${r.displayName} (code is never collected from AWS)`)} });`,
        `    const ${v}CodeKey = new cdk.CfnParameter(this, ${quote(names.key)}, { type: 'String', description: ${quote(`S3 object key of the deployment package for ${r.displayName}`)} });`,
        `    parameters.code[${quote(r.physicalId)}] = { bucket: ${v}CodeBucket.valueAsString, key: ${v}CodeKey.valueAsString };`,
      );
      const envNames =
        (r.observedProperties['environmentVariableNames'] as string[] | undefined) ?? [];
      if (envNames.length > 0) {
        lines.push(`    parameters.environment[${quote(r.physicalId)}] = {};`);
        for (const env of [...envNames].sort()) {
          const pid = envParameterName(ctx, id, env);
          const pv = `${v}Env${toPascalCase(env)}`;
          lines.push(
            `    const ${pv} = new cdk.CfnParameter(this, ${quote(pid)}, { type: 'String', noEcho: ${isSecretishEnvName(env)}, description: ${quote(`Value of environment variable ${env} for ${r.displayName} (values are never collected from AWS)`)} });`,
            `    parameters.environment[${quote(r.physicalId)}][${quote(env)}] = ${pv}.valueAsString;`,
          );
        }
      }
    }
    lines.push('');
  }

  const varOf = (g: GroupName) => g;
  for (const o of outputs) {
    const args: string[] = [...o.uses.map((g) => varOf(g))];
    if (o.hasParameters) args.push('parameters');
    const propsArg =
      args.length > 0
        ? `, { ${args.map((a) => (a === 'parameters' ? 'parameters' : a)).join(', ')} }`
        : '';
    lines.push(
      `    const ${o.group} = new ${o.className}(this, ${quote(toPascalCase(o.group))}${propsArg});`,
    );
  }
  lines.push('    void [' + outputs.map((o) => o.group).join(', ') + '];', '  }', '}', '');
  return { path: `lib/stacks/${stackFileBase(plan)}.ts`, content: lines.join('\n') };
}

export function appFile(plan: ReconstructionPlan): GeneratedFile {
  const stack = plan.stacks[0]!;
  return {
    path: 'bin/app.ts',
    content: [
      '#!/usr/bin/env node',
      '// Generated by Cloud to Code.',
      "import * as cdk from 'aws-cdk-lib';",
      `import { ${stack.name} } from '../lib/stacks/${stackFileBase(plan)}';`,
      '',
      'const app = new cdk.App();',
      '// The stack is environment-agnostic on purpose. Set `env` to deploy to a specific account/region.',
      `new ${stack.name}(app, ${quote(stack.name)});`,
      '',
    ].join('\n'),
  };
}

export function packageFiles(plan: ReconstructionPlan): GeneratedFile[] {
  const name = kebab(plan.applicationName);
  const pkg = {
    name,
    version: '0.1.0',
    private: true,
    description: `AWS CDK app reconstructed from running infrastructure by Cloud to Code (${plan.applicationName}). Review before deploying.`,
    scripts: {
      build: 'tsc',
      test: 'vitest run',
      synth: 'cdk synth',
      diff: 'cdk diff',
    },
    dependencies: {
      'aws-cdk-lib': CDK_LIB_VERSION,
      constructs: '^10.5.0',
    },
    devDependencies: {
      '@types/node': '^22.0.0',
      'aws-cdk': '^2.1100.0',
      'ts-node': '^10.9.2',
      typescript: '~5.9.0',
      vitest: '^3.2.0',
    },
  };
  const tsconfig = {
    compilerOptions: {
      target: 'ES2022',
      module: 'node16',
      moduleResolution: 'node16',
      lib: ['es2022'],
      strict: true,
      esModuleInterop: true,
      skipLibCheck: true,
      outDir: 'dist',
      types: ['node'],
    },
    include: ['bin', 'lib', 'test'],
    exclude: ['node_modules', 'dist', 'cdk.out'],
  };
  const cdkJson = { app: 'npx ts-node --prefer-ts-exts bin/app.ts', output: 'cdk.out' };
  return [
    { path: 'package.json', content: `${JSON.stringify(pkg, null, 2)}\n` },
    { path: 'tsconfig.json', content: `${JSON.stringify(tsconfig, null, 2)}\n` },
    { path: 'cdk.json', content: `${JSON.stringify(cdkJson, null, 2)}\n` },
    { path: '.gitignore', content: 'node_modules/\ndist/\ncdk.out/\n*.js\n!vitest.config.js\n' },
  ];
}
