import type { GenContext } from '../context.js';
import { GenerationError } from '../types.js';
import { RuleRun, type RuleResult } from './common.js';

interface KeyElement {
  attributeName: string;
  keyType: 'HASH' | 'RANGE';
}
interface AttributeDefinition {
  attributeName: string;
  attributeType: 'S' | 'N' | 'B';
}
interface Projection {
  projectionType?: 'ALL' | 'KEYS_ONLY' | 'INCLUDE';
  nonKeyAttributes?: string[];
}
interface Throughput {
  readCapacityUnits?: number;
  writeCapacityUnits?: number;
}
interface Index {
  indexName: string;
  keySchema: KeyElement[];
  projection?: Projection;
  provisionedThroughput?: Throughput;
}

const ATTRIBUTE_TYPES = { S: 'STRING', N: 'NUMBER', B: 'BINARY' } as const;
const STREAM_VIEW_TYPES = new Set(['KEYS_ONLY', 'NEW_IMAGE', 'OLD_IMAGE', 'NEW_AND_OLD_IMAGES']);

export function emitTable(ctx: GenContext, id: string): RuleResult {
  const run = new RuleRun(ctx, id, 'data/dynamodb-table@1');
  const { t } = run;
  const out = ctx.out;
  const v = ctx.varName(id);
  out.use('dynamodb');
  out.use('cdk');

  const defs = t.take<AttributeDefinition[]>('attributeDefinitions') ?? [];
  const attr = (name: string) => {
    const def = defs.find((d) => d.attributeName === name);
    if (!def)
      throw new GenerationError(
        'missing-attribute',
        `Table ${run.r.displayName}: no attribute definition for key "${name}".`,
      );
    return `{ name: ${ctx.str(name)}, type: dynamodb.AttributeType.${ATTRIBUTE_TYPES[def.attributeType]} }`;
  };

  const keys = t.take<KeyElement[]>('keySchema') ?? [];
  const hash = keys.find((k) => k.keyType === 'HASH');
  const range = keys.find((k) => k.keyType === 'RANGE');
  if (!hash)
    throw new GenerationError(
      'missing-key',
      `Table ${run.r.displayName} has no HASH key in the snapshot.`,
    );

  const props: string[] = [`partitionKey: ${attr(hash.attributeName)},`];
  if (range) props.push(`sortKey: ${attr(range.attributeName)},`);

  const billing = t.take<string>('billingMode') ?? 'PAY_PER_REQUEST';
  const throughput = t.take<Throughput>('provisionedThroughput');
  if (billing === 'PROVISIONED') {
    props.push('billingMode: dynamodb.BillingMode.PROVISIONED,');
    if (throughput?.readCapacityUnits) props.push(`readCapacity: ${throughput.readCapacityUnits},`);
    if (throughput?.writeCapacityUnits)
      props.push(`writeCapacity: ${throughput.writeCapacityUnits},`);
  } else {
    props.push('billingMode: dynamodb.BillingMode.PAY_PER_REQUEST,');
  }

  const stream = t.take<{ streamEnabled?: boolean; streamViewType?: string }>(
    'streamSpecification',
  );
  if (stream?.streamEnabled) {
    if (stream.streamViewType && STREAM_VIEW_TYPES.has(stream.streamViewType)) {
      props.push(`stream: dynamodb.StreamViewType.${stream.streamViewType},`);
    } else {
      run.unresolve(
        'streamSpecification',
        `Unknown stream view type ${String(stream.streamViewType)}; stream not enabled.`,
      );
    }
  }
  t.omitted('latestStreamArn', 'Stream ARNs are regenerated by AWS for the new table.');

  if (t.take<boolean>('pointInTimeRecoveryEnabled')) {
    props.push('pointInTimeRecoverySpecification: { pointInTimeRecoveryEnabled: true },');
  }
  if (t.take<boolean>('deletionProtectionEnabled')) props.push('deletionProtection: true,');

  const ttl = t.take<{ attributeName?: string; enabled?: boolean }>('timeToLive');
  if (ttl?.enabled && ttl.attributeName)
    props.push(`timeToLiveAttribute: ${ctx.str(ttl.attributeName)},`);

  const tableClass = t.take<string>('tableClass');
  if (tableClass === 'STANDARD_INFREQUENT_ACCESS')
    props.push('tableClass: dynamodb.TableClass.STANDARD_INFREQUENT_ACCESS,');

  const sse = t.take<{ sseType?: string; kmsMasterKeyArn?: string }>('sseDescription');
  if (sse?.sseType === 'KMS') {
    if (sse.kmsMasterKeyArn) {
      out.use('kms');
      props.push('encryption: dynamodb.TableEncryption.CUSTOMER_MANAGED,');
      props.push(
        `encryptionKey: kms.Key.fromKeyArn(this, ${ctx.str(`${ctx.logicalId(id)}Key`)}, ${ctx.str(sse.kmsMasterKeyArn)}),`,
      );
    } else {
      props.push('encryption: dynamodb.TableEncryption.AWS_MANAGED,');
    }
  }

  t.omitted(
    'tableName',
    'Physical name not set so the new table cannot collide with the existing one.',
  );
  props.push('removalPolicy: cdk.RemovalPolicy.RETAIN,');

  run.header();
  out.line(`const ${v} = new dynamodb.Table(this, ${ctx.str(ctx.logicalId(id))}, {`);
  for (const p of props) out.line(`  ${p}`);
  out.line('});');

  const indexProps = (idx: Index, kind: 'gsi' | 'lsi'): string[] => {
    const h = idx.keySchema.find((k) => k.keyType === 'HASH');
    const r = idx.keySchema.find((k) => k.keyType === 'RANGE');
    const lines = [`indexName: ${ctx.str(idx.indexName)},`];
    if (kind === 'gsi' && h) lines.push(`partitionKey: ${attr(h.attributeName)},`);
    if (r) lines.push(`sortKey: ${attr(r.attributeName)},`);
    const pt = idx.projection?.projectionType;
    if (pt) lines.push(`projectionType: dynamodb.ProjectionType.${pt},`);
    if (pt === 'INCLUDE' && idx.projection?.nonKeyAttributes?.length) {
      lines.push(
        `nonKeyAttributes: [${idx.projection.nonKeyAttributes.map((n) => ctx.str(n)).join(', ')}],`,
      );
    }
    if (kind === 'gsi' && billing === 'PROVISIONED') {
      if (idx.provisionedThroughput?.readCapacityUnits)
        lines.push(`readCapacity: ${idx.provisionedThroughput.readCapacityUnits},`);
      if (idx.provisionedThroughput?.writeCapacityUnits)
        lines.push(`writeCapacity: ${idx.provisionedThroughput.writeCapacityUnits},`);
    }
    return lines;
  };
  for (const idx of t.take<Index[]>('globalSecondaryIndexes') ?? []) {
    out.line(`${v}.addGlobalSecondaryIndex({`);
    for (const l of indexProps(idx, 'gsi')) out.line(`  ${l}`);
    out.line('});');
  }
  for (const idx of t.take<Index[]>('localSecondaryIndexes') ?? []) {
    out.line(`${v}.addLocalSecondaryIndex({`);
    for (const l of indexProps(idx, 'lsi')) out.line(`  ${l}`);
    out.line('});');
  }

  run.tags(v);
  run.register('tables', v);
  return run.result('L2');
}
